import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const S = vm.createContext({});
vm.runInContext(fs.readFileSync(new URL('../State.js', import.meta.url), 'utf8'), S);

test('autosave retains newer drafts, coalesces edits, retries failure and orders deletion', () => {
  const state = S.create();
  S.edit(state, 1, 'first'); S.flush(state);
  assert.equal(S.next(state).notes, 'first');
  S.edit(state, 1, 'second'); S.flush(state);
  S.edit(state, 1, 'latest'); S.flush(state);
  assert.equal(state.queue.length, 1);
  S.finish(state, true);
  assert.equal(state.drafts[1].notes, 'latest');
  assert.equal(S.next(state).notes, 'latest'); S.finish(state, false);
  assert.equal(S.next(state), null);
  assert.equal(state.drafts[1].notes, 'latest');
  S.edit(state, 1, 'retry newest'); S.retry(state);
  assert.equal(S.next(state).notes, 'retry newest'); S.finish(state, true);
  assert.equal(state.drafts[1], undefined);
  S.edit(state, 2, 'pending'); S.flush(state); S.next(state);
  S.edit(state, 2, 'newer'); S.flush(state);
  S.enqueue(state, { op: 'deleteBookmark', id: 2 });
  assert.equal(state.drafts[2].notes, 'newer');
  S.finish(state, true);
  assert.equal(S.next(state).op, 'deleteBookmark'); S.finish(state, true);
  assert.equal(state.drafts[2], undefined);
  assert.equal(S.next(state), null);
  S.edit(state, 3, 'a'); S.flush(state); S.next(state);
  S.edit(state, 3, 'b'); S.flush(state);
  S.edit(state, 3, 'a'); S.flush(state);
  S.finish(state, true);
  assert.equal(S.next(state), null, 'changing back to the in-flight draft cancels obsolete queued text');
  assert.ok(S.safeUrl('https://[::1]:8000/a?b=c#d'));
  for (const url of ['javascript:alert(1)', 'https://u:p@a.test', 'https://a.test\\@b.test']) assert.equal(S.safeUrl(url), false);
});
